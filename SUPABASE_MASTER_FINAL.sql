    RAISE EXCEPTION 'INVALID_WITHDRAWAL_STATUS';
  END IF;
  UPDATE public.withdrawals
  SET status=lower(p_status), note=p_note, processed_at=CASE WHEN lower(p_status) IN ('approved','rejected','completed','cancelled') THEN now() ELSE processed_at END
  WHERE id=p_id RETURNING * INTO r;
  IF NOT FOUND THEN RAISE EXCEPTION 'WITHDRAWAL_NOT_FOUND'; END IF;
  RETURN to_jsonb(r);
END $$;

