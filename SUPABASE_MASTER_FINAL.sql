-- ============================================================
-- BAYAR.GG SETTLEMENT 70/30
-- ============================================================

CREATE OR REPLACE FUNCTION public.settle_bayargg_order(
 p_order_id uuid,
 p_invoice_id text,
 p_gateway_status text,
 p_final_amount numeric,
 p_gateway_payload jsonb DEFAULT '{}'::jsonb
)
RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public
AS $$
DECLARE
 o public.orders%ROWTYPE;
 seller_share numeric;
 platform_fee numeric;
 tx_exists boolean;
 plan text;
 days integer;
BEGIN
 SELECT * INTO o FROM public.orders WHERE id=p_order_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'ORDER_NOT_FOUND'; END IF;

 IF lower(coalesce(o.status,'')) IN ('paid','success','completed') THEN RETURN true; END IF;
 IF lower(coalesce(p_gateway_status,'')) NOT IN ('paid','settled','success') THEN RETURN false;
 END IF;
 IF round(coalesce(p_final_amount,0),0)<>round(coalesce(o.amount,0),0)
 THEN RAISE EXCEPTION 'AMOUNT_MISMATCH'; END IF;

 UPDATE public.orders
 SET status='paid',
     paid_at=coalesce(paid_at,now()),
     payment_reference=coalesce(p_invoice_id,payment_reference),
     gateway_payload=coalesce(p_gateway_payload,'{}'::jsonb)
 WHERE id=o.id;

 IF lower(coalesce(o.item_type,''))='account_plan' THEN
   plan=lower(coalesce(o.item_id,''));
   IF plan='premium' THEN
     UPDATE public.profiles SET is_premium=true WHERE id=o.buyer_id;
   ELSE
     days:=CASE plan WHEN 'subscription_1' THEN 1
                     WHEN 'subscription_3' THEN 3
                     WHEN 'subscription_7' THEN 7 ELSE 0 END;
     IF days>0 THEN
       UPDATE public.profiles
       SET subscription_until=
         greatest(coalesce(subscription_until,now()),now())
         +(days||' days')::interval
       WHERE id=o.buyer_id;
     END IF;
   END IF;
 ELSE
   seller_share:=round(coalesce(o.amount,0)*0.70,2);
   platform_fee:=round(coalesce(o.amount,0)-seller_share,2);

   INSERT INTO public.wallets(user_id,balance,available_balance,pending_balance)
   VALUES(o.seller_id,seller_share,seller_share,0)
   ON CONFLICT(user_id) DO UPDATE SET
     balance=public.wallets.balance+excluded.balance,
     available_balance=public.wallets.available_balance+excluded.available_balance,
     updated_at=now();

   SELECT EXISTS(
     SELECT 1 FROM public.transactions
     WHERE user_id=o.seller_id
       AND reference='bayargg-order:'||o.id::text
   ) INTO tx_exists;

   IF NOT tx_exists THEN
     INSERT INTO public.transactions(
       user_id,amount,fee,net_amount,type,status,reference,description
     )
     VALUES(
       o.seller_id,seller_share,platform_fee,seller_share,
       'sale_earning','completed',
       'bayargg-order:'||o.id::text,
       'Marketplace sale 70/30'
     );
   END IF;

   IF lower(coalesce(o.item_type,'')) IN ('product','code') THEN
     UPDATE public.products
     SET sales_count=sales_count+1,updated_at=now()
     WHERE id=o.product_id;
   ELSIF lower(coalesce(o.item_type,''))='telegram_product' THEN
     UPDATE public.telegram_products
     SET sales_count=sales_count+1,updated_at=now()
     WHERE id=o.product_id;
   END IF;

   INSERT INTO public.purchases(
     buyer_id,product_id,order_id,item_type,item_id,item_title,amount,status
   )
   VALUES(
     o.buyer_id,o.product_id,o.id,o.item_type,o.item_id,o.item_title,o.amount,'completed'
   );
 END IF;

 RETURN true;
END $$;

